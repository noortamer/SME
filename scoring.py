# normalize
weights = {k: np.array(v)/sum(v) for k, v in weights.items()}


# age from start_year
df = df.merge(companies[["الرقم_الضريبي","start_year","اسم_الشركة"]], on="الرقم_الضريبي", how="left")
df["start_year"] = df["start_year"].fillna(df["السنة"])
df["عمر_المنشأة"] = (df["السنة"] - df["start_year"]).clip(lower=0) + 1

# growth (keep NaN for first year)
df = df.sort_values(["الرقم_الضريبي","السنة"])
df["نمو_المبيعات"]   = df.groupby("الرقم_الضريبي")["المبيعات_جنيه"].pct_change()
df["نمو_الموظفين"]   = df.groupby("الرقم_الضريبي")["الموظفون"].pct_change()

# revenue / capital (avoid div-by-zero → NaN)
df["العائد_على_رأس_المال"] = df["الإيرادات_جنيه"] / df["رأس_المال_المدفوع_جنيه"].replace(0, np.nan)
df.replace([np.inf, -np.inf], np.nan, inplace=True)

# ---------- Percentiles per (year × sector) ----------
features = ["المبيعات_جنيه","نمو_المبيعات","الموظفون","نمو_الموظفين","عمر_المنشأة","العائد_على_رأس_المال","branches"]

def pct_in_group(s: pd.Series) -> pd.Series:
    s = s.fillna(s.median())
    if s.nunique(dropna=False) <= 1:
        return pd.Series(0.5, index=s.index)                # neutral if no variation
    return s.rank(pct=True, method="average")               # 0..1 percentiles

for col in features:
    df[col+"_p"] = df.groupby(["السنة","القطاع"], dropna=False)[col].transform(pct_in_group)

# ---------- Weighted score (0–10) ----------
def row_score(row):
    w = weights.get(row["القطاع"], np.ones(len(features))/len(features))
    vals = row[[c+"_p" for c in features]].to_numpy(dtype=float)
    return np.dot(vals, w) * 10

df["score"] = df.apply(row_score, axis=1).round(2)

# ---------- Save ----------
df.to_csv(r"data/finalscores.csv", index=False, encoding="utf-8-sig")
